// Bundles the Vite build into one self-contained HTML file at play/index.html.
//
// Everything (Three.js, the game code, the stylesheet) is inlined, so the file
// can be served from a raw CDN such as raw.githack.com or statically.io - or just
// opened from disk, since an inline module script needs no network fetch.
//
//   npm run build:play
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = join(root, 'dist');
const outDir = join(root, 'play');
const outFile = join(outDir, 'index.html');

function readDist(assetPath) {
  // Vite emits absolute-ish paths like "./assets/index-abc123.js".
  const clean = assetPath.replace(/^\.?\//, '');
  return readFileSync(join(dist, clean), 'utf8');
}

let html = readFileSync(join(dist, 'index.html'), 'utf8');

// --- Inline the stylesheet(s).
html = html.replace(/<link[^>]+rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (_match, href) => {
  const css = readDist(href);
  return `<style>\n${css}\n</style>`;
});

// --- Inline the module script(s).
html = html.replace(/<script([^>]*)src="([^"]+)"([^>]*)><\/script>/g, (_match, before, src, after) => {
  const attrs = `${before} ${after}`;
  const isModule = /type="module"/.test(attrs);
  const js = readDist(src)
    // A literal </script> inside the bundle would close the tag early.
    .replace(/<\/script>/gi, '<\\/script>');
  return `<script${isModule ? ' type="module"' : ''}>\n${js}\n</script>`;
});

// Drop the module preload hints: there is nothing left to preload.
html = html.replace(/<link[^>]+rel="modulepreload"[^>]*>\s*/g, '');

const banner = `<!--
  Sea of Scoundrels - single-file build. Generated by scripts/build-single-file.mjs;
  edit the sources under src/ instead of this file.

  A fan-made Sea of Thieves parody. Not affiliated with, endorsed by, or connected
  to Sea of Thieves, Rare Ltd. or Microsoft.
-->
`;
html = html.replace(/^<!doctype html>/i, `<!doctype html>\n${banner}`);

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, html);

const sizeMb = (statSync(outFile).size / 1024 / 1024).toFixed(2);
const leftovers = readdirSync(join(dist, 'assets')).filter((f) => !/\.(js|css)$/.test(f));
console.log(`Wrote ${outFile} (${sizeMb} MB)`);
if (leftovers.length) console.warn(`Warning: unreferenced dist assets not inlined: ${leftovers.join(', ')}`);
