export function measureSmallText(text) {
  let w = 0;
  for (const ch of text.toUpperCase()) { const g = SMALL[ch] || SMALL['-']; w += g.split('/')[0].length + 1; }
  return w - 1;
}

// Draws centered 3x5 text into an RGBA pixel buffer of size w x h.
export function drawSmallText(buf, w, h, text, color) {
  const up = text.toUpperCase();
  const tw = measureSmallText(up);
  let x = Math.floor((w - tw) / 2);
  const y0 = Math.floor((h - 5) / 2);
  for (const ch of up) {
    const rows = (SMALL[ch] || SMALL['-']).split('/');
    for (let r = 0; r < rows.length; r++) for (let c = 0; c < rows[r].length; c++) {
      if (rows[r][c] !== '#') continue;
      const px = x + c, py = y0 + r;
      if (px < 0 || py < 0 || px >= w || py >= h) continue;
      const i = (py * w + px) * 4;
      buf[i] = color[0]; buf[i + 1] = color[1]; buf[i + 2] = color[2]; buf[i + 3] = 255;
    }
    x += rows[0].length + 1;
  }
}
