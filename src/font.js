const GLYPHS = {};
for (const k in G) {
  const rows = G[k].split('/');
  GLYPHS[k] = { rows, w: rows[0].length };
}
const FALLBACK = GLYPHS['?'];

export function glyphWidth(ch) {
  const g = GLYPHS[ch] || FALLBACK;
  return g.w;
}

export function measureText(text, scale = 1) {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1) * scale;
}

// Draws text onto a 2D canvas context using filled rects. Colors are CSS strings.
export function drawText(ctx, text, x, y, scale = 2, color = '#ffffff', shadow = true) {
  let cx = x;
  if (shadow) {
    ctx.fillStyle = shadowColor(color);
    let sx = x;
    for (const ch of text) {
      const g = GLYPHS[ch] || FALLBACK;
      for (let r = 0; r < g.rows.length; r++) {
        const row = g.rows[r];
        for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(sx + c * scale + scale, y + r * scale + scale, scale, scale);
      }
      sx += (g.w + 1) * scale;
    }
  }
  ctx.fillStyle = color;
  for (const ch of text) {
    const g = GLYPHS[ch] || FALLBACK;
    for (let r = 0; r < g.rows.length; r++) {
      const row = g.rows[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
    }
    cx += (g.w + 1) * scale;
  }
  return cx - x;
}

function shadowColor(color) {
  // Minecraft draws the shadow at 1/4 brightness of the text colour.
  if (color.startsWith('#') && (color.length === 7 || color.length === 4)) {
    let r, g, b;
    if (color.length === 7) { r = parseInt(color.slice(1, 3), 16); g = parseInt(color.slice(3, 5), 16); b = parseInt(color.slice(5, 7), 16); }
    else { r = parseInt(color[1] + color[1], 16); g = parseInt(color[2] + color[2], 16); b = parseInt(color[3] + color[3], 16); }
    return `rgb(${r >> 2},${g >> 2},${b >> 2})`;
  }
  return 'rgba(0,0,0,0.75)';
}

